#!/usr/bin/env python3
"""Regenerate EXPERIMENTS.md from experiments/log.jsonl.

Local fields come from start/result/promoted/champion/abandoned/crashed events (latest wins).
Official fields come only from `official` events and are shown in separate columns, so local and
official numbers never mix. Validation vs Final: local columns are split by track; official runs are
Final except E000 and E008 (official Validation)."""
import json, pathlib

root = pathlib.Path(__file__).resolve().parent
OFFICIAL_VAL = {"E000", "E008"}
STATUS_EVENTS = {"result", "promoted", "champion", "abandoned", "crashed", "official", "baseline"}
rows, order = {}, []
for line in (root / "log.jsonl").read_text().splitlines():
    if not line.strip():
        continue
    e = json.loads(line)
    i = e["id"]
    if i not in rows:
        rows[i] = {}
        order.append(i)
    r, ev = rows[i], e.get("event")
    if ev == "official":
        for k_src, k_dst in (("official_S", "off_S"), ("eta_vs_base", "off_eta"), ("j_per_req", "off_j"),
                             ("slo_met", "off_slo"), ("accuracy", "off_acc")):
            if e.get(k_src) is not None:
                r[k_dst] = e[k_src]
    else:
        for k in ("parent", "change", "val_S", "final_S", "eta_vs_base", "j_per_req", "slo_met",
                  "p95_tpot_ms", "accuracy", "lesson"):
            if e.get(k) is not None:
                r[k] = e[k]
    if ev in STATUS_EVENTS and e.get("status"):
        r["status"] = e["status"]
    if ev == "official" and e.get("lesson"):
        r["off_lesson"] = e["lesson"]

cols = [("id", "id"), ("parent", "parent"), ("change", "change"), ("status", "status"),
        ("val_S", "local Val S"), ("final_S", "local Final S"), ("j_per_req", "local J/req"),
        ("slo_met", "local SLO-met"), ("accuracy", "local acc %"),
        ("off", "OFFICIAL S (track)"), ("off_j", "off. J/req"), ("off_slo", "off. SLO-met"), ("off_acc", "off. acc %"),
        ("lesson", "lesson")]
out = ["# Experiments", "",
       "Generated by `experiments/render.py` from `experiments/log.jsonl` (append-only event log). Per-experiment",
       "details: `experiments/<id>/{card,result}.md`, exact launch command `experiments/<id>/config.sh` (as run; later",
       "edits to `configs/<id>.sh` only moved the wrapper path), server logs `experiments/<id>/server*.log`.",
       "Local columns = our local grader (`local_grader/`, scored vs our local baseline; local Val S is depressed by",
       "agent-class noise, n=20). OFFICIAL columns = organizer grader. Official track is Final unless marked (val).",
       "Local timestamps in log.jsonl for E000-E007 were hand-entered and can be up to ~30 min off; grader run IDs carry",
       "true start times.", "",
       "| " + " | ".join(c[1] for c in cols) + " |", "|" + "---|" * len(cols)]
for i in order:
    r = rows[i]
    r["id"] = i
    if "off_S" in r:
        r["off"] = f'{r["off_S"]} ({"val" if i in OFFICIAL_VAL else "final"})'
    cells = []
    for k, _ in cols:
        v = r.get(k, "")
        cells.append(str(v).replace("|", "/"))
    out.append("| " + " | ".join(cells) + " |")
kf = root.parent / "KEY_FINDINGS.md"
out += ["", "## Key findings", "", kf.read_text() if kf.exists() else "_(none yet)_"]
(root.parent / "EXPERIMENTS.md").write_text("\n".join(out) + "\n")
